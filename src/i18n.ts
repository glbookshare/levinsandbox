export function detectLanguage(languages: readonly string[]): Language {
 return languages[0]?.toLowerCase().split('-')[0] === 'de' ? 'de' : 'en';
}
let language: Language = detectLanguage(typeof navigator === 'undefined' ? [] : navigator.languages);
export const getLanguage = () => language;
export function t(english: string): string { return language === 'de' ? german[english] ?? english : english; }
const sourceText = new WeakMap<Text,string>();
const sourceLabels = new WeakMap<Element,string>();
// Capture static text once; never rebuild the canvas or its event handlers.
export function captureTranslations(root: HTMLElement) {
 const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
 while(walker.nextNode()) { const node = walker.currentNode as Text; sourceText.set(node,node.data); }
 root.querySelectorAll('[aria-label]').forEach(el => sourceLabels.set(el,el.getAttribute('aria-label')!));
}
export function setLanguage(next: Language, root: HTMLElement) {
 language = next; document.documentElement.lang = next;
 document.title = 'Pocket Physics · ' + (next === 'de' ? 'Eine kleine Welt voller Möglichkeiten' : 'A little world of possibilities');
 const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
 while(walker.nextNode()) {
  const node = walker.currentNode as Text;
  if(node.parentElement?.closest('[data-dynamic], #toast, #language')) continue;
  const original = sourceText.get(node);
  if(original !== undefined) {
   const keys = Object.keys(german).sort((a,b)=>b.length-a.length);
   const pattern = new RegExp(keys.map(key=>key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
   const translated = next === 'de' ? original.replace(pattern,match=>german[match]) : original;
   node.data = translated;
  }
 }
 root.querySelectorAll('[aria-label]').forEach(el=>{const original=sourceLabels.get(el);if(original)el.setAttribute('aria-label',t(original));});
}
